--     접수는 REG_DATE, 처리 완료는 ANSWER_DATE 기준. 이번 주 접수가 지난주보다 많아야 정상
SELECT
  SUM(REG_DATE >= DATE_SUB(CURDATE(), INTERVAL 7 DAY) AND REG_DATE < CURDATE()) AS 이번주_접수,
  SUM(REG_DATE >= DATE_SUB(CURDATE(), INTERVAL 14 DAY) AND REG_DATE < DATE_SUB(CURDATE(), INTERVAL 7 DAY)) AS 지난주_접수,
  SUM(STATUS = 'DONE' AND ANSWER_DATE >= DATE_SUB(CURDATE(), INTERVAL 7 DAY) AND ANSWER_DATE < CURDATE()) AS 이번주_처리완료,
  SUM(STATUS = 'DONE' AND ANSWER_DATE >= DATE_SUB(CURDATE(), INTERVAL 14 DAY) AND ANSWER_DATE < DATE_SUB(CURDATE(), INTERVAL 7 DAY)) AS 지난주_처리완료
FROM report;

-- (c) 이번 주 신고가 많은 노선 TOP 5 (대시보드 막대와 같은 값)
SELECT ROUTE_NO, COUNT(*) AS 건수 FROM report
WHERE REG_DATE >= DATE_SUB(CURDATE(), INTERVAL 7 DAY) AND REG_DATE < CURDATE()
GROUP BY ROUTE_NO ORDER BY 건수 DESC, ROUTE_NO LIMIT 5;

-- (d) 이번 주 신고가 많은 유형 TOP 5
SELECT T.TYPE_NAME, COUNT(*) AS 건수 FROM report R INNER JOIN report_type T ON R.TYPE_NO = T.TYPE_NO
WHERE R.REG_DATE >= DATE_SUB(CURDATE(), INTERVAL 7 DAY) AND R.REG_DATE < CURDATE()
GROUP BY T.TYPE_NO, T.TYPE_NAME ORDER BY 건수 DESC, T.TYPE_NO LIMIT 5;

